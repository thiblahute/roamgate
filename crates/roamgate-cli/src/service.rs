//! The part of Roamgate's own service manager `roamgate update` and
//! `roamgate rollback` use (config/service-definitions,
//! config/service-manager, config/launchd-environment): where the service
//! and its environment file are, the published herdr-gui service it may
//! still manage, reading the environment file without running it, whether
//! the service runs, and restarting it. Install, uninstall, status and
//! reload come with the rest of the CLI (S18).

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use roamgate_base::paths::DataContext;
use roamgate_exec::service::{
    RunCommand, ServicePlatform, WindowsTaskQuery, argv, escape_systemd_exec_path,
    launchd_job_running, powershell_literal, query_windows_task, resolve_service_platform,
    restart_windows_task, xml_escape,
};
use sha2::{Digest, Sha256};

pub const SERVICE_LABEL: &str = "dev.roamgate";
pub const GENERATED_MARKER: &str = "Generated by roamgate service install.";
pub const LEGACY_GENERATED_MARKER: &str = "Generated by herdr-gui service install.";
/// `launchctl print` of a service that does not exist.
const LAUNCHD_SERVICE_NOT_FOUND_EXIT_CODE: i32 = 113;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ServicePaths {
    pub config: PathBuf,
    pub definition: PathBuf,
    pub task_name: Option<String>,
    pub stdout_log: Option<PathBuf>,
    pub stderr_log: Option<PathBuf>,
}

fn user_key(base: &Path) -> String {
    hex::encode(Sha256::digest(
        base.display().to_string().to_lowercase().as_bytes(),
    ))[..16]
        .to_owned()
}

fn roaming(home: &Path, app_data: Option<&Path>) -> PathBuf {
    app_data
        .map(Path::to_path_buf)
        .unwrap_or_else(|| home.join("AppData").join("Roaming"))
}

pub fn resolve_service_paths(
    platform: ServicePlatform,
    home: &Path,
    app_data: Option<&Path>,
) -> ServicePaths {
    if platform == ServicePlatform::WindowsTask {
        let base = roaming(home, app_data).join("roamgate");
        return ServicePaths {
            config: base.join("roamgate.env"),
            definition: base.join("roamgate-task.ps1"),
            task_name: Some(format!("{SERVICE_LABEL}-{}", user_key(&base))),
            stdout_log: Some(base.join("roamgate.stdout.log")),
            stderr_log: Some(base.join("roamgate.stderr.log")),
        };
    }
    let config = home.join(".config").join("roamgate").join("roamgate.env");
    if platform == ServicePlatform::Systemd {
        return ServicePaths {
            config,
            definition: home.join(".config/systemd/user/roamgate.service"),
            task_name: None,
            stdout_log: None,
            stderr_log: None,
        };
    }
    ServicePaths {
        config,
        definition: home
            .join("Library/LaunchAgents")
            .join(format!("{SERVICE_LABEL}.plist")),
        task_name: None,
        stdout_log: Some(home.join("Library/Logs/roamgate.stdout.log")),
        stderr_log: Some(home.join("Library/Logs/roamgate.stderr.log")),
    }
}

/// The published <= 0.7.0 identities, kept until an explicit cut-over.
pub fn resolve_legacy_service_paths(
    platform: ServicePlatform,
    home: &Path,
    app_data: Option<&Path>,
) -> ServicePaths {
    let base = if platform == ServicePlatform::WindowsTask {
        roaming(home, app_data).join("herdr-gui")
    } else {
        home.join(".config").join("herdr-gui")
    };
    let config = base.join("herdr-gui.env");
    if platform == ServicePlatform::WindowsTask {
        return ServicePaths {
            config,
            definition: base.join("herdr-gui-task.ps1"),
            task_name: Some(format!("dev.herdr.herdr-gui-{}", user_key(&base))),
            stdout_log: None,
            stderr_log: None,
        };
    }
    ServicePaths {
        config,
        definition: if platform == ServicePlatform::Systemd {
            home.join(".config/systemd/user/herdr-gui.service")
        } else {
            home.join("Library/LaunchAgents/dev.herdr.herdr-gui.plist")
        },
        task_name: None,
        stdout_log: None,
        stderr_log: None,
    }
}

fn text(path: &Option<PathBuf>) -> String {
    path.as_ref()
        .map(|path| path.display().to_string())
        .unwrap_or_default()
}

pub fn render_systemd_service(binary: &str, config: &str, preserved: Option<&str>) -> String {
    format!(
        "# {GENERATED_MARKER}
[Unit]
Description=Roamgate
Wants=network-online.target
After=network-online.target

[Service]
Type=simple
EnvironmentFile=-{}
ExecStart={}
Restart=always
RestartSec=2
TimeoutStopSec=15

[Install]
WantedBy=default.target
",
        escape_systemd_exec_path(config),
        preserved
            .map(str::to_owned)
            .unwrap_or_else(|| escape_systemd_exec_path(binary))
    )
}

pub fn render_windows_task_definition(
    binary: &str,
    paths: &ServicePaths,
) -> Result<String, String> {
    let Some(task) = &paths.task_name else {
        return Err("Windows service task name is missing".into());
    };
    Ok(format!(
        "\u{FEFF}# {GENERATED_MARKER}
$ErrorActionPreference = \"Stop\"
$taskName = {}
$user = [Security.Principal.WindowsIdentity]::GetCurrent().Name
$action = New-ScheduledTaskAction -Execute {} -Argument {}
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $user
$principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Limited
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -ExecutionTimeLimit ([TimeSpan]::Zero) -MultipleInstances IgnoreNew -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1)
Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Principal $principal -Settings $settings -Force | Out-Null
",
        powershell_literal(task),
        powershell_literal(binary),
        powershell_literal(&format!("service run \"{}\"", paths.config.display())),
    ))
}

pub fn render_launchd_service(binary: &str, paths: &ServicePaths) -> String {
    let config = paths.config.display().to_string();
    let arguments = [
        "/bin/sh",
        "-c",
        "set -a; if [ -f \"$1\" ]; then . \"$1\"; fi; set +a; exec \"$2\"",
        "roamgate-service",
        &config,
        binary,
    ]
    .iter()
    .map(|argument| format!("    <string>{}</string>", xml_escape(argument)))
    .collect::<Vec<_>>()
    .join("\n");
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!-- {GENERATED_MARKER} -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>{SERVICE_LABEL}</string>

  <key>ProgramArguments</key>
  <array>
{arguments}
  </array>

  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>ThrottleInterval</key>
  <integer>2</integer>
  <key>ProcessType</key>
  <string>Background</string>

  <key>StandardOutPath</key>
  <string>{}</string>
  <key>StandardErrorPath</key>
  <string>{}</string>
</dict>
</plist>
"#,
        xml_escape(&text(&paths.stdout_log)),
        xml_escape(&text(&paths.stderr_log)),
    )
}

/// The Roamgate side of a service runtime.
#[derive(Debug, Clone)]
pub struct ServiceRuntime {
    pub platform: String,
    pub home: PathBuf,
    pub app_data: Option<PathBuf>,
    pub exec_path: PathBuf,
    pub uid: Option<u32>,
}

impl ServiceRuntime {
    fn data(&self) -> DataContext {
        DataContext::new(
            self.home.clone(),
            if self.platform == "win32" {
                roamgate_base::paths::Platform::Windows
            } else {
                roamgate_base::paths::Platform::Unix
            },
            self.app_data.clone(),
        )
    }
}

fn absolute(path: &Path) -> PathBuf {
    roamgate_base::paths::resolve(path)
}

/// Whether a legacy definition is exactly the published 0.7.0 one for this
/// executable (customised ones need their owner).
fn is_published_legacy_definition(
    platform: ServicePlatform,
    runtime: &ServiceRuntime,
    paths: &ServicePaths,
) -> bool {
    let binary = absolute(&runtime.exec_path).display().to_string();
    let mut expected = match platform {
        ServicePlatform::Systemd => {
            render_systemd_service(&binary, &paths.config.display().to_string(), None)
        }
        ServicePlatform::WindowsTask => match render_windows_task_definition(&binary, paths) {
            Ok(text) => text,
            Err(_) => return false,
        },
        ServicePlatform::Launchd => render_launchd_service(
            &binary,
            &ServicePaths {
                stdout_log: Some(runtime.home.join("Library/Logs/herdr-gui.stdout.log")),
                stderr_log: Some(runtime.home.join("Library/Logs/herdr-gui.stderr.log")),
                ..paths.clone()
            },
        ),
    };
    expected = expected.replacen(GENERATED_MARKER, LEGACY_GENERATED_MARKER, 1);
    if platform == ServicePlatform::Launchd {
        expected = expected
            .replacen("<string>dev.roamgate</string>", "<string>dev.herdr.herdr-gui</string>", 1)
            .replacen(
                "<string>roamgate-service</string>",
                "<string>herdr-gui-service</string>",
                1,
            )
            .replacen(
                "  <key>RunAtLoad</key>",
                "  <key>EnvironmentVariables</key>\n  <dict>\n    <key>HERDR_GUI_RESTART_SUPERVISOR</key>\n    <string>1</string>\n  </dict>\n\n  <key>RunAtLoad</key>",
                1,
            );
    }
    std::fs::read_to_string(&paths.definition)
        .map(|text| text.replace("\r\n", "\n") == expected)
        .unwrap_or(false)
}

fn basename(path: &Path) -> String {
    path.file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_default()
}

fn stem(path: &Path, suffix: &str) -> String {
    let name = basename(path);
    name.strip_suffix(suffix).map(str::to_owned).unwrap_or(name)
}

/// Whether the managed service exists and its manager runs it: the
/// Roamgate one, else a published legacy one.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ServiceStatus {
    pub installed: bool,
    pub active: bool,
    pub definition: PathBuf,
}

pub fn roamgate_service_status(
    runtime: &ServiceRuntime,
    run: &dyn RunCommand,
) -> Result<ServiceStatus, String> {
    let platform = resolve_service_platform(&runtime.platform)?;
    let mut paths = resolve_service_paths(platform, &runtime.home, runtime.app_data.as_deref());
    if !paths.definition.exists() {
        let legacy =
            resolve_legacy_service_paths(platform, &runtime.home, runtime.app_data.as_deref());
        runtime
            .data()
            .assert_safe_data_path(&legacy.definition)
            .map_err(|error| error.to_string())?;
        if legacy.definition.exists() && is_published_legacy_definition(platform, runtime, &legacy)
        {
            paths = legacy;
        }
    }
    let installed = paths.definition.exists();
    let status = |active| ServiceStatus {
        installed,
        active,
        definition: paths.definition.clone(),
    };
    if !installed {
        return Ok(status(false));
    }
    Ok(match platform {
        ServicePlatform::Systemd => status(
            run.run(
                &argv(&[
                    "systemctl",
                    "--user",
                    "is-active",
                    "--quiet",
                    &basename(&paths.definition),
                ]),
                true,
            ) == 0,
        ),
        ServicePlatform::Launchd => match runtime.uid {
            None => status(false),
            Some(uid) => {
                let (code, printed) = run.capture(&argv(&[
                    "launchctl",
                    "print",
                    &format!("gui/{uid}/{}", stem(&paths.definition, ".plist")),
                ]));
                status(code == 0 && launchd_job_running(&printed))
            }
        },
        ServicePlatform::WindowsTask => {
            let quiet = Quiet(run);
            status(matches!(
                query_windows_task(paths.task_name.as_deref().unwrap_or(""), &quiet),
                WindowsTaskQuery::Exists { active: true }
            ))
        }
    })
}

/// A [`RunCommand`] whose runs are all quiet.
struct Quiet<'a>(&'a dyn RunCommand);

impl RunCommand for Quiet<'_> {
    fn run(&self, argv: &[String], _quiet: bool) -> i32 {
        self.0.run(argv, true)
    }
}

fn service_exists(
    platform: ServicePlatform,
    runtime: &ServiceRuntime,
    paths: &ServicePaths,
    run: &dyn RunCommand,
    identity: &str,
) -> Result<bool, String> {
    if paths.definition.exists() {
        return Ok(true);
    }
    match platform {
        ServicePlatform::WindowsTask => {
            let Some(task) = &paths.task_name else {
                return Err("Windows service task name is missing".into());
            };
            match query_windows_task(task, run) {
                WindowsTaskQuery::Error { code } => Err(format!(
                    "cannot check {identity} scheduled task (exit {code}); no service changes made"
                )),
                WindowsTaskQuery::Exists { .. } => Ok(true),
                WindowsTaskQuery::Missing => Ok(false),
            }
        }
        ServicePlatform::Systemd => {
            let code = run.run(
                &argv(&[
                    "systemctl",
                    "--user",
                    "--no-pager",
                    "status",
                    &basename(&paths.definition),
                ]),
                true,
            );
            match code {
                0 | 3 => Ok(true),
                4 => Ok(false),
                code => Err(format!(
                    "cannot check {identity} systemd service (exit {code}); no service changes made"
                )),
            }
        }
        ServicePlatform::Launchd => {
            let Some(uid) = runtime.uid else {
                return Err("cannot determine the current user id for launchd".into());
            };
            if run.run(&argv(&["launchctl", "print", &format!("gui/{uid}")]), true) != 0 {
                return Err("cannot check launchd user domain; no service changes made".into());
            }
            let code = run.run(
                &argv(&[
                    "launchctl",
                    "print",
                    &format!("gui/{uid}/{}", stem(&paths.definition, ".plist")),
                ]),
                true,
            );
            match code {
                0 => Ok(true),
                LAUNCHD_SERVICE_NOT_FOUND_EXIT_CODE => Ok(false),
                code => Err(format!(
                    "cannot check {identity} launchd service (exit {code}); no service changes made"
                )),
            }
        }
    }
}

/// The definition `service` commands manage: a published legacy one, else
/// Roamgate's; refuses an unmanaged legacy service.
fn managed_service_paths(
    platform: ServicePlatform,
    runtime: &ServiceRuntime,
    run: &dyn RunCommand,
    log: &mut dyn FnMut(&str),
) -> Result<ServicePaths, String> {
    let current = resolve_service_paths(platform, &runtime.home, runtime.app_data.as_deref());
    let legacy = resolve_legacy_service_paths(platform, &runtime.home, runtime.app_data.as_deref());
    runtime
        .data()
        .assert_safe_data_path(&legacy.definition)
        .map_err(|error| error.to_string())?;
    if legacy.definition.exists() && is_published_legacy_definition(platform, runtime, &legacy) {
        if service_exists(platform, runtime, &current, run, "Roamgate")? {
            return Err("both Roamgate and legacy services exist; resolve the duplicate services with the previous binary or native service manager before continuing; no service changes made".into());
        }
        log(&format!(
            "Managing legacy service: {}; its name and configuration are preserved. Uninstall it before installing the new Roamgate service.",
            legacy.definition.display()
        ));
        return Ok(legacy);
    }
    if service_exists(platform, runtime, &legacy, run, "legacy")? {
        return Err(format!(
            "legacy service detected ({}); stop and uninstall it using the previous binary's service uninstall before activating Roamgate. For custom definitions, explicitly disable and archive them yourself. Preserve the legacy config and token. See docs/DEPLOYMENT.md#transition-from-herdr-studio--herdr-gui. --force does not bypass this check.",
            legacy.definition.display()
        ));
    }
    Ok(current)
}

/// `roamgate service restart`: its exit code, its lines through `log` and
/// `error`.
pub fn restart_service(
    runtime: &ServiceRuntime,
    run: &dyn RunCommand,
    log: &mut dyn FnMut(&str),
    error: &mut dyn FnMut(&str),
) -> i32 {
    let result = (|| -> Result<i32, String> {
        let platform = resolve_service_platform(&runtime.platform)?;
        let paths = managed_service_paths(platform, runtime, run, log)?;
        let name = stem(&paths.definition, ".plist");
        Ok(match platform {
            ServicePlatform::Systemd => {
                run.run(&argv(&["systemctl", "--user", "restart", &name]), false)
            }
            ServicePlatform::WindowsTask => {
                let Some(task) = &paths.task_name else {
                    return Err("Windows service task name is missing".into());
                };
                restart_windows_task(task, run)
            }
            ServicePlatform::Launchd => {
                let Some(uid) = runtime.uid else {
                    return Err("cannot determine the current user id for launchd".into());
                };
                run.run(
                    &argv(&["launchctl", "kickstart", "-k", &format!("gui/{uid}/{name}")]),
                    false,
                )
            }
        })
    })();
    match result {
        Ok(code) => code,
        Err(message) => {
            error(&format!("roamgate service: {message}"));
            error("Run `roamgate service --help` for usage.");
            1
        }
    }
}

// ---------------------------------------------------------- environment file

fn decode_value(raw: &str) -> String {
    let bytes = raw.as_bytes();
    if raw.len() >= 2 && (bytes[0] == b'\'' || bytes[0] == b'"') && bytes[raw.len() - 1] == bytes[0]
    {
        raw[1..raw.len() - 1].to_owned()
    } else {
        raw.to_owned()
    }
}

/// `NAME=value` lines, `export` allowed, comments and blank lines skipped.
pub fn parse_environment_entries(
    contents: &str,
    path: &str,
) -> Result<BTreeMap<String, String>, String> {
    let line_re =
        regex::Regex::new(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$").unwrap();
    let mut values = BTreeMap::new();
    for (index, line) in contents.split('\n').enumerate() {
        let line = line.strip_suffix('\r').unwrap_or(line);
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let Some(captures) = line_re.captures(line) else {
            return Err(format!("invalid environment entry at {path}:{}", index + 1));
        };
        values.insert(captures[1].to_owned(), decode_value(&captures[2]));
    }
    Ok(values)
}

fn shell_special(name: &str) -> bool {
    regex::Regex::new(r"^(?:BASH.*|COMP.*|HIST.*|READLINE.*|ENV|IFS|SHELLOPTS|UID|EUID|PPID|SHLVL|RANDOM|SRANDOM|SECONDS|LINENO|OPTIND|OPTARG|GROUPS|DIRSTACK|FUNCNAME|PIPESTATUS|COPROC|MAPFILE|EPOCHREALTIME|EPOCHSECONDS|HOSTNAME|HOSTTYPE|MACHTYPE|OSTYPE|REPLY|_)$")
        .unwrap()
        .is_match(name)
}

/// The non-executable subset of a launchd shell environment file, never
/// sourced: `NAME=value` with quotes, escapes and `$NAME`/`${NAME}` of
/// names defined before (HOME given).
pub fn resolve_launchd_environment(
    contents: &str,
    path: &str,
    home: &str,
) -> Result<BTreeMap<String, String>, String> {
    let chars: Vec<char> = contents.chars().collect();
    let mut values: BTreeMap<String, String> = BTreeMap::new();
    values.insert("HOME".into(), home.to_owned());
    let mut offset = 0usize;
    let fail = |offset: usize, reason: &str| -> String {
        let line = chars[..offset.min(chars.len())]
            .iter()
            .filter(|character| **character == '\n')
            .count()
            + 1;
        format!("invalid launchd environment at {path}:{line}: {reason}")
    };
    if contents.contains('\0') {
        return Err(fail(0, "NUL characters are not supported"));
    }
    let at = |offset: usize| chars.get(offset).copied();
    let starts_with = |offset: usize, text: &str| {
        text.chars()
            .enumerate()
            .all(|(index, character)| at(offset + index) == Some(character))
    };
    let space = |offset: &mut usize| {
        while matches!(at(*offset), Some(' ' | '\t')) {
            *offset += 1;
        }
    };
    let name_at = |offset: usize| -> Option<String> {
        let first = at(offset)?;
        if !(first.is_ascii_alphabetic() || first == '_') {
            return None;
        }
        let mut name = String::new();
        let mut index = offset;
        while let Some(character) = at(index) {
            if character.is_ascii_alphanumeric() || character == '_' {
                name.push(character);
                index += 1;
            } else {
                break;
            }
        }
        Some(name)
    };
    while offset < chars.len() {
        space(&mut offset);
        if at(offset) == Some('#') {
            while offset < chars.len() && chars[offset] != '\n' {
                offset += 1;
            }
        }
        if at(offset) == Some('\n') {
            offset += 1;
            continue;
        }
        if offset == chars.len() {
            break;
        }
        if starts_with(offset, "export") && matches!(at(offset + 6), Some(' ' | '\t')) {
            offset += 6;
            space(&mut offset);
        }
        let Some(name) =
            name_at(offset).filter(|name| at(offset + name.chars().count()) == Some('='))
        else {
            return Err(fail(offset, "expected one NAME=value assignment per line"));
        };
        if shell_special(&name) {
            return Err(fail(
                offset,
                "shell-special variable assignments are not supported",
            ));
        }
        offset += name.chars().count() + 1;
        let mut value = String::new();
        let mut quote: Option<char> = None;
        while offset < chars.len() {
            let character = chars[offset];
            if quote == Some('\'') {
                offset += 1;
                if character == '\'' {
                    quote = None;
                } else {
                    value.push(character);
                }
                continue;
            }
            if Some(character) == quote {
                quote = None;
                offset += 1;
                continue;
            }
            if quote.is_none() {
                if matches!(character, ' ' | '\t' | '\n') {
                    break;
                }
                if character == '\'' || character == '"' {
                    quote = Some(character);
                    offset += 1;
                    continue;
                }
                if ";&|<>()~".contains(character) {
                    return Err(fail(
                        offset,
                        "shell operators and unquoted tilde expansion are not supported",
                    ));
                }
            }
            if character == '`' {
                return Err(fail(offset, "command substitution is not supported"));
            }
            if character == '$' {
                // expandVariable
                let quoted = quote == Some('"');
                offset += 1;
                if starts_with(offset, "\\\n") {
                    return Err(fail(
                        offset,
                        "line continuations inside variable references are not supported",
                    ));
                }
                if !quoted && matches!(at(offset), Some('\'' | '"')) {
                    return Err(fail(offset, "shell-specific quoting is not supported"));
                }
                let braced = at(offset) == Some('{');
                if braced {
                    offset += 1;
                }
                let Some(reference) = name_at(offset) else {
                    if braced || at(offset).is_some_and(|next| "([0123456789@*#?$!-".contains(next))
                    {
                        return Err(fail(
                            offset,
                            "only $NAME and ${NAME} variable expansion is supported",
                        ));
                    }
                    value.push('$');
                    continue;
                };
                offset += reference.chars().count();
                if !braced && starts_with(offset, "\\\n") {
                    return Err(fail(
                        offset,
                        "line continuations inside variable references are not supported",
                    ));
                }
                if braced {
                    if at(offset) != Some('}') {
                        return Err(fail(
                            offset,
                            "only $NAME and ${NAME} variable expansion is supported",
                        ));
                    }
                    offset += 1;
                }
                let Some(known) = values.get(&reference) else {
                    return Err(fail(
                        offset,
                        "define referenced variables earlier in the config (HOME is available)",
                    ));
                };
                value.push_str(&known.clone());
                continue;
            }
            if character == '\\' {
                let Some(escaped) = at(offset + 1) else {
                    return Err(fail(offset, "incomplete escape"));
                };
                if quote.is_none() || "$`\"\\\n".contains(escaped) {
                    if escaped != '\n' {
                        value.push(escaped);
                    }
                    offset += 2;
                    continue;
                }
            }
            value.push(character);
            offset += 1;
        }
        if quote.is_some() {
            return Err(fail(offset, "unterminated quote"));
        }
        values.insert(name, value);
        space(&mut offset);
        if at(offset) == Some('#') {
            while offset < chars.len() && chars[offset] != '\n' {
                offset += 1;
            }
        }
        if offset < chars.len() && chars[offset] != '\n' {
            return Err(fail(offset, "expected one NAME=value assignment per line"));
        }
        if at(offset) == Some('\n') {
            offset += 1;
        }
    }
    Ok(values)
}

/// The values a managed service gets from its environment file, without
/// running anything.
pub fn parse_service_environment(
    contents: &str,
    path: &str,
    platform: ServicePlatform,
    home: &str,
) -> Result<BTreeMap<String, String>, String> {
    if platform != ServicePlatform::Launchd {
        return parse_environment_entries(contents, path);
    }
    let mut values = resolve_launchd_environment(contents, path, home)?;
    // HOME is only an expansion source, not a setting.
    let sets_home = regex::Regex::new(r"(?m)^\s*(?:export\s+)?HOME\s*=")
        .unwrap()
        .is_match(contents);
    if !sets_home {
        values.remove("HOME");
    }
    Ok(values)
}

/// The managed service's environment (readServiceSetup): the current file,
/// else the legacy one, else nothing; an error when it cannot be read.
pub fn read_service_environment(
    runtime: &ServiceRuntime,
) -> Result<BTreeMap<String, String>, String> {
    let platform = resolve_service_platform(&runtime.platform)?;
    let paths = resolve_service_paths(platform, &runtime.home, runtime.app_data.as_deref());
    let legacy = resolve_legacy_service_paths(platform, &runtime.home, runtime.app_data.as_deref());
    let config = [&paths.config, &legacy.config]
        .into_iter()
        .find(|path| path.exists())
        .unwrap_or(&paths.config)
        .clone();
    runtime
        .data()
        .assert_safe_data_path(&config)
        .map_err(|error| error.to_string())?;
    if !config.exists() {
        // The default template sets nothing an update reads.
        return Ok(BTreeMap::new());
    }
    let contents = std::fs::read_to_string(&config).map_err(|error| error.to_string())?;
    parse_service_environment(
        &contents,
        &config.display().to_string(),
        platform,
        &runtime.home.display().to_string(),
    )
}

#[cfg(test)]
mod tests {
    use roamgate_exec::service::fake::Recorder;

    use super::*;

    fn runtime(home: &Path, platform: &str) -> ServiceRuntime {
        ServiceRuntime {
            platform: platform.into(),
            home: home.into(),
            app_data: None,
            exec_path: home.join("bin/roamgate"),
            uid: Some(501),
        }
    }

    #[test]
    fn reads_entries_and_the_launchd_subset_without_running_anything() {
        assert_eq!(
            parse_environment_entries("# c\nexport A='1 2'\nB = \"x\"\n\n", "f").unwrap(),
            BTreeMap::from([("A".into(), "1 2".into()), ("B".into(), "x".into())])
        );
        assert_eq!(
            parse_environment_entries("A=1\nnot an entry\n", "f"),
            Err("invalid environment entry at f:2".into())
        );
        let values = resolve_launchd_environment(
            "A=$HOME/x\nexport B=\"${A} y\" # note\nC='$A'\n",
            "f",
            "/home/me",
        )
        .unwrap();
        assert_eq!(values["A"], "/home/me/x");
        assert_eq!(values["B"], "/home/me/x y");
        assert_eq!(values["C"], "$A");
        for (bad, why) in [
            ("A=$(id)", "only $NAME"),
            ("A=`id`", "command substitution"),
            ("A=1; B=2", "shell operators"),
            ("A=$NOPE", "define referenced variables"),
            ("RANDOM=1", "shell-special"),
            ("A='open", "unterminated quote"),
        ] {
            let error = resolve_launchd_environment(bad, "f", "/h").unwrap_err();
            assert!(error.contains(why), "{bad}: {error}");
        }
        let launchd =
            parse_service_environment("A=1\n", "f", ServicePlatform::Launchd, "/h").unwrap();
        assert!(!launchd.contains_key("HOME"));
    }

    #[test]
    fn reports_the_service_and_restarts_the_managed_one() {
        let home = tempfile::tempdir().unwrap();
        let runtime = runtime(home.path(), "linux");
        let run = Recorder::new(|_| 0);
        let status = roamgate_service_status(&runtime, &run).unwrap();
        assert!(!status.installed && !status.active);
        let paths = resolve_service_paths(ServicePlatform::Systemd, home.path(), None);
        std::fs::create_dir_all(paths.definition.parent().unwrap()).unwrap();
        std::fs::write(&paths.definition, render_systemd_service("/b", "/c", None)).unwrap();
        let status = roamgate_service_status(&runtime, &run).unwrap();
        assert!(status.installed && status.active);
        // The legacy unit is absent (status 4): restart the Roamgate one.
        let run = Recorder::new(|argv| {
            if argv.contains(&"status".to_owned()) {
                4
            } else {
                0
            }
        });
        let (mut out, mut err) = (Vec::new(), Vec::new());
        let code = restart_service(
            &runtime,
            &run,
            &mut |line| out.push(line.to_owned()),
            &mut |line| err.push(line.to_owned()),
        );
        assert_eq!(code, 0);
        assert_eq!(
            run.argvs().last().unwrap(),
            &argv(&["systemctl", "--user", "restart", "roamgate.service"])
        );
        // A legacy service it does not manage stops it.
        let run = Recorder::new(|_| 0);
        assert_eq!(
            restart_service(&runtime, &run, &mut |_| {}, &mut |line| err
                .push(line.to_owned())),
            1
        );
        assert!(
            err[0].starts_with("roamgate service: legacy service detected"),
            "{err:?}"
        );
    }

    #[test]
    fn manages_a_published_legacy_definition() {
        let home = tempfile::tempdir().unwrap();
        let runtime = runtime(home.path(), "linux");
        let legacy = resolve_legacy_service_paths(ServicePlatform::Systemd, home.path(), None);
        std::fs::create_dir_all(legacy.definition.parent().unwrap()).unwrap();
        let published = render_systemd_service(
            &runtime.exec_path.display().to_string(),
            &legacy.config.display().to_string(),
            None,
        )
        .replacen(GENERATED_MARKER, LEGACY_GENERATED_MARKER, 1);
        std::fs::write(&legacy.definition, published).unwrap();
        let run = Recorder::new(|argv| {
            if argv.contains(&"status".to_owned()) {
                4
            } else {
                0
            }
        });
        let status = roamgate_service_status(&runtime, &run).unwrap();
        assert_eq!(status.definition, legacy.definition);
        let mut logged = Vec::new();
        assert_eq!(
            restart_service(
                &runtime,
                &run,
                &mut |line| logged.push(line.to_owned()),
                &mut |_| {}
            ),
            0
        );
        assert!(logged[0].starts_with("Managing legacy service: "));
        assert_eq!(
            run.argvs().last().unwrap(),
            &argv(&["systemctl", "--user", "restart", "herdr-gui.service"])
        );
    }
}
