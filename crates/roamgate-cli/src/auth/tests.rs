//! cli/auth.test.ts.

use serde_json::Value;

use crate::args::{EXIT_FAILURE, EXIT_OK};
use crate::context::testing::TestCli;

fn token() -> String {
    "b".repeat(64)
}

fn token_path(cli: &TestCli) -> std::path::PathBuf {
    cli.in_home(".config/roamgate/auth-token")
}

fn is_token(text: &str) -> bool {
    text.len() == 64
        && text
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

#[tokio::test]
async fn show_masks_the_token_unless_revealed() {
    let cli = TestCli::new();
    cli.write_config("ROAMGATE_PIN=123456\n");
    std::fs::write(token_path(&cli), format!("{}\n", token())).unwrap();
    cli.run_cli(&["auth", "show", "--json"]).await;
    let shown: Value = serde_json::from_str(&cli.output().join("\n")).unwrap();
    assert_eq!(shown["method"], "token");
    assert_eq!(shown["token"], "bbbb...bbbb");
    assert_eq!(shown["pin_enabled"], true);
    let keys: Vec<&String> = shown.as_object().unwrap().keys().collect();
    assert_eq!(
        keys,
        [
            "method",
            "token_path",
            "token",
            "pin_enabled",
            "session_secret_path",
            "session_secret_exists"
        ]
    );
    let before = cli.output().len();
    cli.run_cli(&["auth", "show", "--json", "--reveal"]).await;
    let revealed: Value = serde_json::from_str(&cli.output()[before..].join("\n")).unwrap();
    assert_eq!(revealed["token"], token());
}

#[tokio::test]
async fn rotate_writes_a_fresh_valid_token_and_prints_new_urls() {
    let cli = TestCli::new();
    cli.write_config("HOST=127.0.0.1\n");
    std::fs::write(token_path(&cli), format!("{}\n", token())).unwrap();
    assert_eq!(cli.run_cli(&["auth", "rotate"]).await, EXIT_OK);
    let rotated = std::fs::read_to_string(token_path(&cli)).unwrap();
    let rotated = rotated.trim();
    assert!(is_token(rotated));
    assert_ne!(rotated, token());
    assert_eq!(
        cli.output(),
        [
            format!(
                "Rotated the login token in {}.",
                cli.shown(".config/roamgate/auth-token")
            ),
            "Every signed-in browser must sign in again with the new URL.".into(),
            "The managed service is not running; restart any foreground roamgate process to apply."
                .into(),
            format!("Open: http://localhost:8787/?token={rotated}"),
        ]
    );
}

#[tokio::test]
async fn rotate_refuses_services_that_use_a_fixed_password() {
    let cli = TestCli::new();
    cli.write_config("ROAMGATE_PASSWORD=correct-horse-battery\n");
    assert_eq!(cli.run_cli(&["auth", "rotate"]).await, EXIT_FAILURE);
    assert!(!token_path(&cli).exists());
}

#[tokio::test]
async fn revoke_sessions_discards_the_signing_secret_under_the_runtime_home() {
    let cli = TestCli::new();
    cli.write_config("");
    let secret = cli.in_home(".config/roamgate/session-secret.json");
    roamgate_base::session_secret::load_or_create_session_secret(
        &cli.context.service().data(),
        &["credential"],
        &secret,
    )
    .unwrap();
    assert!(secret.exists());
    assert_eq!(
        cli.run_cli(&["auth", "revoke-sessions", "--no-restart"])
            .await,
        EXIT_OK
    );
    assert!(!secret.exists());
    assert_eq!(cli.run_cli(&["auth", "revoke-sessions"]).await, EXIT_OK);
    assert!(
        cli.output()
            .last()
            .unwrap()
            .contains("no sessions to revoke")
    );
}

#[tokio::test]
async fn restarts_a_running_managed_service_after_rotation() {
    // No legacy herdr-gui unit exists (systemctl status exits 4 for it).
    let cli = TestCli::with(
        |argv| {
            Some(if argv.iter().any(|arg| arg == "herdr-gui.service") {
                4
            } else {
                0
            })
        },
        |_| None,
    );
    cli.write_config("");
    let units = cli.in_home(".config/systemd/user");
    std::fs::create_dir_all(&units).unwrap();
    std::fs::write(
        units.join("roamgate.service"),
        "# Generated by roamgate service install.\n",
    )
    .unwrap();
    assert_eq!(cli.run_cli(&["auth", "rotate"]).await, EXIT_OK);
    assert!(cli.commands().contains(&vec![
        "systemctl".to_owned(),
        "--user".into(),
        "restart".into(),
        "roamgate.service".into()
    ]));
    assert!(cli.output().contains(&"Restarted the service.".to_owned()));
}

#[tokio::test]
async fn rotate_repairs_a_corrupt_token_and_revoke_sessions_ignores_it() {
    let cli = TestCli::new();
    cli.write_config("");
    std::fs::write(token_path(&cli), "truncated\n").unwrap();
    assert_eq!(cli.run_cli(&["auth", "show"]).await, EXIT_OK);
    let line = cli
        .output()
        .into_iter()
        .find(|line| line.starts_with("Token:"))
        .unwrap();
    assert!(line.contains("invalid"), "{line}");
    assert_eq!(
        cli.run_cli(&["auth", "revoke-sessions", "--no-restart"])
            .await,
        EXIT_OK
    );
    assert_eq!(cli.run_cli(&["auth", "rotate"]).await, EXIT_OK);
    assert!(is_token(
        std::fs::read_to_string(token_path(&cli)).unwrap().trim()
    ));
}
