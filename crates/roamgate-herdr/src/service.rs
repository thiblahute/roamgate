//! The user service running `herdr server` (herdr/service): a systemd user
//! unit, a launchd LaunchAgent or a per-user Scheduled Task, written only
//! over a definition Roamgate generated, then started.

use std::path::{Path, PathBuf};

use roamgate_exec::service::{
    RunCommand, ServicePlatform, WindowsTaskQuery, argv, escape_systemd_exec_path,
    powershell_literal, query_windows_task, register_windows_task, restart_windows_task,
    win32_dirname, write_definition, xml_escape,
};
use sha2::{Digest, Sha256};

pub const HERDR_SERVICE_MARKER: &str = "Generated by roamgate herdr setup.";
pub const HERDR_SERVICE_LABEL: &str = "dev.roamgate.herdr";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HerdrServicePaths {
    pub definition: PathBuf,
    pub task_name: Option<String>,
    pub stdout_log: Option<PathBuf>,
    pub stderr_log: Option<PathBuf>,
}

pub fn resolve_herdr_service_paths(
    platform: ServicePlatform,
    home: &Path,
    app_data: Option<&Path>,
) -> HerdrServicePaths {
    match platform {
        ServicePlatform::WindowsTask => {
            let base = app_data
                .map(Path::to_path_buf)
                .unwrap_or_else(|| home.join("AppData").join("Roaming"))
                .join("roamgate");
            let key = hex::encode(Sha256::digest(
                base.display().to_string().to_lowercase().as_bytes(),
            ));
            HerdrServicePaths {
                definition: base.join("herdr-task.ps1"),
                task_name: Some(format!("{HERDR_SERVICE_LABEL}-{}", &key[..16])),
                stdout_log: None,
                stderr_log: None,
            }
        }
        ServicePlatform::Systemd => HerdrServicePaths {
            definition: home
                .join(".config")
                .join("systemd")
                .join("user")
                .join("roamgate-herdr.service"),
            task_name: None,
            stdout_log: None,
            stderr_log: None,
        },
        ServicePlatform::Launchd => HerdrServicePaths {
            definition: home
                .join("Library")
                .join("LaunchAgents")
                .join(format!("{HERDR_SERVICE_LABEL}.plist")),
            task_name: None,
            stdout_log: Some(
                home.join("Library")
                    .join("Logs")
                    .join("roamgate-herdr.stdout.log"),
            ),
            stderr_log: Some(
                home.join("Library")
                    .join("Logs")
                    .join("roamgate-herdr.stderr.log"),
            ),
        },
    }
}

pub fn render_herdr_systemd_service(binary_path: &str) -> String {
    format!(
        "# {HERDR_SERVICE_MARKER}
[Unit]
Description=Herdr server (managed by Roamgate)
Wants=network-online.target
After=network-online.target

[Service]
Type=simple
ExecStart={} server
Restart=always
RestartSec=2
TimeoutStopSec=15

[Install]
WantedBy=default.target
",
        escape_systemd_exec_path(binary_path)
    )
}

fn path_text(path: &Option<PathBuf>) -> String {
    path.as_ref()
        .map(|path| path.display().to_string())
        .unwrap_or_default()
}

pub fn render_herdr_launchd_service(binary_path: &str, paths: &HerdrServicePaths) -> String {
    let arguments = [binary_path, "server"]
        .iter()
        .map(|argument| format!("    <string>{}</string>", xml_escape(argument)))
        .collect::<Vec<_>>()
        .join("\n");
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!-- {HERDR_SERVICE_MARKER} -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>{HERDR_SERVICE_LABEL}</string>

  <key>ProgramArguments</key>
  <array>
{arguments}
  </array>

  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>ThrottleInterval</key>
  <integer>2</integer>
  <key>ProcessType</key>
  <string>Background</string>

  <key>StandardOutPath</key>
  <string>{}</string>
  <key>StandardErrorPath</key>
  <string>{}</string>
</dict>
</plist>
"#,
        xml_escape(&path_text(&paths.stdout_log)),
        xml_escape(&path_text(&paths.stderr_log)),
    )
}

pub fn render_herdr_windows_task(
    binary_path: &str,
    paths: &HerdrServicePaths,
) -> Result<String, String> {
    let Some(task_name) = &paths.task_name else {
        return Err("Windows service task name is missing".into());
    };
    Ok(format!(
        "\u{FEFF}# {HERDR_SERVICE_MARKER}
$ErrorActionPreference = \"Stop\"
$taskName = {}
$user = [Security.Principal.WindowsIdentity]::GetCurrent().Name
$action = New-ScheduledTaskAction -Execute {} -Argument {} -WorkingDirectory {}
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $user
$principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Limited
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -ExecutionTimeLimit ([TimeSpan]::Zero) -MultipleInstances IgnoreNew -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1)
Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Principal $principal -Settings $settings -Force | Out-Null
",
        powershell_literal(task_name),
        powershell_literal(binary_path),
        powershell_literal("server"),
        powershell_literal(&win32_dirname(binary_path)),
    ))
}

/// Where and how the service runs.
pub struct HerdrServiceDeps<'a> {
    pub platform: ServicePlatform,
    pub home: PathBuf,
    pub app_data: Option<PathBuf>,
    pub uid: Option<u32>,
    pub run: &'a dyn RunCommand,
}

/// The current user's id (launchd's `gui/<uid>` domain).
pub fn current_uid() -> Option<u32> {
    #[cfg(unix)]
    {
        Some(rustix::process::getuid().as_raw())
    }
    #[cfg(not(unix))]
    {
        None
    }
}

fn assert_definition_writable(path: &Path) -> Result<(), String> {
    if path.exists()
        && !std::fs::read_to_string(path)
            .unwrap_or_default()
            .contains(HERDR_SERVICE_MARKER)
    {
        return Err(format!(
            "{} was not generated by roamgate; remove it yourself before rerunning herdr setup",
            path.display()
        ));
    }
    Ok(())
}

fn succeeded(code: i32, operation: &str) -> Result<(), String> {
    if code != 0 {
        return Err(format!("{operation} failed (exit {code})"));
    }
    Ok(())
}

/// Installs (or replaces) the user service running `herdr server` and
/// starts it. The definition is regenerated on every call, so a changed
/// binary path takes effect.
pub fn install_herdr_service(
    binary_path: &str,
    deps: &HerdrServiceDeps,
) -> Result<HerdrServicePaths, String> {
    let paths = resolve_herdr_service_paths(deps.platform, &deps.home, deps.app_data.as_deref());
    assert_definition_writable(&paths.definition)?;
    if let Some(log) = &paths.stdout_log
        && let Some(dir) = log.parent()
    {
        std::fs::create_dir_all(dir).map_err(|error| error.to_string())?;
    }
    let write = |content: String| {
        write_definition(&paths.definition, &content).map_err(|error| error.to_string())
    };
    let run = deps.run;
    match deps.platform {
        ServicePlatform::Systemd => {
            write(render_herdr_systemd_service(binary_path))?;
            succeeded(
                run.run(&argv(&["systemctl", "--user", "daemon-reload"]), false),
                "systemd daemon-reload",
            )?;
            succeeded(
                run.run(
                    &argv(&["systemctl", "--user", "enable", "roamgate-herdr.service"]),
                    false,
                ),
                "systemd service enable",
            )?;
            // Explicit: `enable` does not restart an active service.
            succeeded(
                run.run(
                    &argv(&["systemctl", "--user", "restart", "roamgate-herdr.service"]),
                    false,
                ),
                "systemd service start",
            )?;
        }
        ServicePlatform::Launchd => {
            let Some(uid) = deps.uid else {
                return Err("cannot determine the current user id for launchd".into());
            };
            write(render_herdr_launchd_service(binary_path, &paths))?;
            let domain = format!("gui/{uid}");
            let service = format!("{domain}/{HERDR_SERVICE_LABEL}");
            if run.run(&argv(&["launchctl", "print", &service]), true) == 0 {
                succeeded(
                    run.run(&argv(&["launchctl", "bootout", &service]), false),
                    "launchd service replacement",
                )?;
            }
            succeeded(
                run.run(
                    &argv(&[
                        "launchctl",
                        "bootstrap",
                        &domain,
                        &paths.definition.display().to_string(),
                    ]),
                    false,
                ),
                "launchd service start",
            )?;
        }
        ServicePlatform::WindowsTask => {
            write(render_herdr_windows_task(binary_path, &paths)?)?;
            succeeded(
                register_windows_task(&paths.definition.display().to_string(), run),
                "scheduled task registration",
            )?;
            succeeded(
                restart_windows_task(paths.task_name.as_deref().unwrap_or(""), run),
                "scheduled task start",
            )?;
        }
    }
    Ok(paths)
}

/// Whether the service is installed and its manager runs it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ServiceState {
    pub installed: bool,
    pub active: bool,
}

pub fn herdr_service_status(deps: &HerdrServiceDeps) -> ServiceState {
    let paths = resolve_herdr_service_paths(deps.platform, &deps.home, deps.app_data.as_deref());
    let installed = paths.definition.exists();
    let active = match deps.platform {
        ServicePlatform::Systemd => {
            deps.run.run(
                &argv(&[
                    "systemctl",
                    "--user",
                    "is-active",
                    "--quiet",
                    "roamgate-herdr.service",
                ]),
                true,
            ) == 0
        }
        ServicePlatform::Launchd => match deps.uid {
            None => false,
            Some(uid) => {
                deps.run.run(
                    &argv(&[
                        "launchctl",
                        "print",
                        &format!("gui/{uid}/{HERDR_SERVICE_LABEL}"),
                    ]),
                    true,
                ) == 0
            }
        },
        ServicePlatform::WindowsTask => match &paths.task_name {
            None => false,
            Some(task) => matches!(
                query_windows_task(task, deps.run),
                WindowsTaskQuery::Exists { active: true }
            ),
        },
    };
    ServiceState { installed, active }
}

#[cfg(test)]
mod tests {
    use roamgate_exec::service::fake::Recorder;

    use super::*;

    fn deps<'a>(
        platform: ServicePlatform,
        home: &Path,
        run: &'a dyn RunCommand,
    ) -> HerdrServiceDeps<'a> {
        HerdrServiceDeps {
            platform,
            home: home.into(),
            app_data: None,
            uid: None,
            run,
        }
    }

    #[test]
    fn uses_per_platform_user_service_locations() {
        let home = tempfile::tempdir().unwrap();
        let home = home.path();
        assert_eq!(
            resolve_herdr_service_paths(ServicePlatform::Systemd, home, None).definition,
            home.join(".config/systemd/user/roamgate-herdr.service")
        );
        let launchd = resolve_herdr_service_paths(ServicePlatform::Launchd, home, None);
        assert_eq!(
            launchd.definition,
            home.join("Library/LaunchAgents")
                .join(format!("{HERDR_SERVICE_LABEL}.plist"))
        );
        assert!(path_text(&launchd.stdout_log).contains("roamgate-herdr.stdout.log"));
        let windows = resolve_herdr_service_paths(
            ServicePlatform::WindowsTask,
            Path::new("C:\\test-home"),
            Some(Path::new("C:\\test-home\\AppData\\Roaming")),
        );
        assert!(
            windows
                .definition
                .display()
                .to_string()
                .contains("herdr-task.ps1")
        );
        assert!(
            windows
                .task_name
                .unwrap()
                .starts_with(&format!("{HERDR_SERVICE_LABEL}-"))
        );
    }

    #[test]
    fn systemd_runs_herdr_server_with_restart_supervision() {
        let unit = render_herdr_systemd_service("/opt/herdr bin/herdr");
        assert!(unit.contains(HERDR_SERVICE_MARKER));
        assert!(unit.contains("ExecStart=/opt/herdr\\x20bin/herdr server"));
        assert!(unit.contains("Restart=always"));
        assert!(unit.contains("WantedBy=default.target"));
    }

    #[test]
    fn launchd_keeps_the_server_alive_with_log_files() {
        let home = tempfile::tempdir().unwrap();
        let plist = render_herdr_launchd_service(
            "/usr/local/bin/herdr",
            &resolve_herdr_service_paths(ServicePlatform::Launchd, home.path(), None),
        );
        assert!(plist.contains(HERDR_SERVICE_MARKER));
        assert!(plist.contains(&format!("<string>{HERDR_SERVICE_LABEL}</string>")));
        assert!(plist.contains("<string>/usr/local/bin/herdr</string>"));
        assert!(plist.contains("<string>server</string>"));
        assert!(plist.contains("<key>KeepAlive</key>"));
    }

    #[test]
    fn windows_task_starts_herdr_server_at_logon_from_its_install_directory() {
        let script = render_herdr_windows_task(
            "C:\\herdr\\herdr.exe",
            &HerdrServicePaths {
                definition: "C:\\cfg\\herdr-task.ps1".into(),
                task_name: Some("dev.roamgate.herdr-abc123".into()),
                stdout_log: None,
                stderr_log: None,
            },
        )
        .unwrap();
        assert!(script.contains(HERDR_SERVICE_MARKER));
        assert!(script.contains("$taskName = 'dev.roamgate.herdr-abc123'"));
        assert!(script.contains("-Execute 'C:\\herdr\\herdr.exe'"));
        assert!(script.contains("-Argument 'server'"));
        assert!(script.contains("-WorkingDirectory 'C:\\herdr'"));
    }

    #[test]
    fn writes_the_unit_and_runs_the_systemd_activation_sequence() {
        let home = tempfile::tempdir().unwrap();
        let run = Recorder::new(|_| 0);
        let paths = install_herdr_service(
            "/opt/herdr/herdr",
            &deps(ServicePlatform::Systemd, home.path(), &run),
        )
        .unwrap();
        assert!(
            std::fs::read_to_string(&paths.definition)
                .unwrap()
                .contains("ExecStart=/opt/herdr/herdr server")
        );
        assert_eq!(
            run.argvs(),
            vec![
                argv(&["systemctl", "--user", "daemon-reload"]),
                argv(&["systemctl", "--user", "enable", "roamgate-herdr.service"]),
                argv(&["systemctl", "--user", "restart", "roamgate-herdr.service"]),
            ]
        );
    }

    #[test]
    fn replaces_a_loaded_launchd_service_before_bootstrapping() {
        let home = tempfile::tempdir().unwrap();
        let run = Recorder::new(|_| 0);
        let mut deps = deps(ServicePlatform::Launchd, home.path(), &run);
        deps.uid = Some(501);
        install_herdr_service("/usr/local/bin/herdr", &deps).unwrap();
        let commands = run.argvs();
        assert_eq!(
            commands[0],
            argv(&[
                "launchctl",
                "print",
                &format!("gui/501/{HERDR_SERVICE_LABEL}")
            ])
        );
        assert_eq!(
            commands[1],
            argv(&[
                "launchctl",
                "bootout",
                &format!("gui/501/{HERDR_SERVICE_LABEL}")
            ])
        );
        assert_eq!(&commands[2][..2], &argv(&["launchctl", "bootstrap"])[..]);
    }

    #[test]
    fn fails_when_an_activation_command_fails() {
        let home = tempfile::tempdir().unwrap();
        let run = Recorder::new(|_| 1);
        assert_eq!(
            install_herdr_service(
                "/opt/herdr/herdr",
                &deps(ServicePlatform::Systemd, home.path(), &run)
            ),
            Err("systemd daemon-reload failed (exit 1)".into())
        );
    }

    #[test]
    fn refuses_to_replace_a_definition_not_generated_by_roamgate() {
        let home = tempfile::tempdir().unwrap();
        let paths = resolve_herdr_service_paths(ServicePlatform::Systemd, home.path(), None);
        std::fs::create_dir_all(paths.definition.parent().unwrap()).unwrap();
        std::fs::write(
            &paths.definition,
            "[Service]\nExecStart=/custom/herdr server\n",
        )
        .unwrap();
        let run = Recorder::new(|_| 0);
        let error = install_herdr_service(
            "/opt/herdr/herdr",
            &deps(ServicePlatform::Systemd, home.path(), &run),
        )
        .unwrap_err();
        assert!(error.contains("was not generated by roamgate"), "{error}");
    }

    #[test]
    fn only_running_windows_tasks_are_active() {
        let home = tempfile::tempdir().unwrap();
        let app_data = tempfile::tempdir().unwrap();
        let paths = resolve_herdr_service_paths(
            ServicePlatform::WindowsTask,
            home.path(),
            Some(app_data.path()),
        );
        std::fs::create_dir_all(paths.definition.parent().unwrap()).unwrap();
        std::fs::write(&paths.definition, HERDR_SERVICE_MARKER).unwrap();
        for code in [0, 4, 3, 5] {
            let run = Recorder::new(move |_| code);
            let mut deps = deps(ServicePlatform::WindowsTask, home.path(), &run);
            deps.app_data = Some(app_data.path().into());
            assert_eq!(
                herdr_service_status(&deps),
                ServiceState {
                    installed: true,
                    active: code == 0
                }
            );
        }
    }

    #[test]
    fn reports_systemd_installation_and_activity() {
        let home = tempfile::tempdir().unwrap();
        let paths = resolve_herdr_service_paths(ServicePlatform::Systemd, home.path(), None);
        let down = Recorder::new(|_| 1);
        assert_eq!(
            herdr_service_status(&deps(ServicePlatform::Systemd, home.path(), &down)),
            ServiceState {
                installed: false,
                active: false
            }
        );
        std::fs::create_dir_all(paths.definition.parent().unwrap()).unwrap();
        std::fs::write(&paths.definition, HERDR_SERVICE_MARKER).unwrap();
        let up = Recorder::new(|_| 0);
        assert_eq!(
            herdr_service_status(&deps(ServicePlatform::Systemd, home.path(), &up)),
            ServiceState {
                installed: true,
                active: true
            }
        );
    }
}
