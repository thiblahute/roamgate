fn deserialize_client_shell_agent_status<'de, D>(
    deserializer: D,
) -> Result<crate::schema::AgentStatus, D::Error>
where
    D: serde::Deserializer<'de>,
{
    if !deserializer.is_human_readable() {
        return crate::schema::AgentStatus::deserialize(deserializer);
    }
    let value = String::deserialize(deserializer)?;
    Ok(match value.as_str() {
        "idle" => crate::schema::AgentStatus::Idle,
        "working" => crate::schema::AgentStatus::Working,
        "blocked" => crate::schema::AgentStatus::Blocked,
        "done" => crate::schema::AgentStatus::Done,
        _ => crate::schema::AgentStatus::Unknown,
    })
}

