/**
 * The parts of the contract produced from the code rather than written:
 * CLI help goldens, the SQL of each database, and the digest of the
 * inventory. The check compares each with the files under contract/.
 */
import { createHash } from "node:crypto";
import type { Inventory } from "./inventory";

/** The database each module's SQL belongs to: its file in storage/sqlite. */
export const SQL_FILES: Record<string, string> = {
  "activity/store.ts": "activity.sql",
  "activity/reader.ts": "activity.sql",
  "archive/store.ts": "archive-index.sql",
  "archive/text-repo.ts": "archive-index.sql",
  "assistant/task-storage.ts": "tasks.sql",
  "assistant/durable-storage.ts": "pi-durable-execution.sql",
  "review/storage.ts": "reviews.sql",
  "cli/history.ts": "reviews.sql",
};

/** A database's .sql file: each module's statements under its name. */
export function sqlFile(sections: Record<string, string[]>): string {
  const body = Object.entries(sections)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([module, statements]) =>
        `-- module: server/src/${module}\n${statements
          .map((statement) => `${statement.replace(/;\s*$/, "")};`)
          .join("\n")}`,
    )
    .join("\n\n");
  return `-- The statements the server runs on this database, per module, in
-- source order, whitespace collapsed, \${...} where the code puts a value.
-- Generated by scripts/contract/scaffold.ts --regenerate and compared with
-- the code by scripts/contract/check.test.ts.

${body}
`;
}

/** The statements per module of a contract .sql file. */
export function parseSqlFile(text: string): Record<string, string[]> {
  const out: Record<string, string[]> = {};
  let module: string | undefined;
  for (const line of text.split("\n")) {
    const header = /^-- module: server\/src\/(.+)$/.exec(line);
    if (header) {
      module = header[1]!;
      out[module] = [];
    } else if (module && line && !line.startsWith("--"))
      out[module]!.push(line.replace(/;$/, ""));
  }
  return out;
}

/** A stable digest of the inventory, recorded in contract.json. */
export function inventoryDigest(inventory: Inventory): string {
  const canonical = Object.keys(inventory)
    .sort()
    .map(
      (key) =>
        `${key}\n${[...inventory[key as keyof Inventory]].sort().join("\n")}`,
    )
    .join("\n\n");
  return createHash("sha256").update(canonical).digest("hex");
}

type Command = {
  name: string;
  help: () => string;
  run: (args: string[], context: unknown) => Promise<unknown>;
};

/** Commands whose help is printed by their own parser (`<cmd> --help`). */
const DELEGATED_HELP = new Set(["service", "herdr", "plugin"]);

/**
 * The help each command prints, as `help/<name>.txt` (standard output) or
 * `help/<name>.stderr.txt`, plus the top-level and server help.
 */
export async function cliGoldens(): Promise<Record<string, string>> {
  const cli = (await import("../../server/src/cli/index")) as unknown as {
    cliCommands: () => Command[];
    topLevelHelp: (commands: readonly Command[]) => string;
  };
  const config = (await import("../../server/src/config/server-config")) as {
    serverOptionsHelp: () => string;
  };
  const commands = cli.cliCommands();
  const out: Record<string, string> = {
    "help/roamgate.txt": `${cli.topLevelHelp(commands)}\n`,
    "help/server.txt": `${config.serverOptionsHelp()}\n`,
  };
  for (const command of commands) {
    if (!DELEGATED_HELP.has(command.name)) {
      out[`help/${command.name}.txt`] = `${command.help()}\n`;
      continue;
    }
    const stdout: string[] = [];
    const stderr: string[] = [];
    const log = console.log;
    const error = console.error;
    console.log = (...args: unknown[]) => stdout.push(args.join(" "));
    console.error = (...args: unknown[]) => stderr.push(args.join(" "));
    try {
      await command.run(["--help"], {
        version: "0.0.0",
        runtime: {
          platform: "linux",
          arch: "x64",
          homeDir: "/home/user",
          execPath: "/opt/roamgate/roamgate",
          argv: [],
          env: {},
        },
        runCommand: () => {
          throw new Error("help must not run commands");
        },
        captureCommand: () => {
          throw new Error("help must not run commands");
        },
        log: (message: string) => stdout.push(message),
        error: (message: string) => stderr.push(message),
      });
    } finally {
      console.log = log;
      console.error = error;
    }
    if (stdout.length)
      out[`help/${command.name}.txt`] = `${stdout.join("\n")}\n`;
    if (stderr.length)
      out[`help/${command.name}.stderr.txt`] = `${stderr.join("\n")}\n`;
  }
  return out;
}
